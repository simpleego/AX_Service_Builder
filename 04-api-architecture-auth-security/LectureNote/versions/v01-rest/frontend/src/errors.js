// =============================================================
// errors.js — 서버 오류 코드를 사용자가 읽기 쉬운 한국어 문장으로 바꾼다.
// =============================================================

// 서버가 보내는 오류 코드(왼쪽)와 화면에 보여줄 문장(오른쪽)의 대응표.
const MESSAGES = {
  TODO_NOT_FOUND: '할 일을 찾을 수 없습니다. 이미 삭제되었을 수 있습니다.', // 404
  VALIDATION_ERROR: '입력값을 확인하세요. 제목은 1~200자여야 합니다.',     // 422
  INTERNAL_ERROR: '서버 오류가 발생했습니다. 잠시 후 다시 시도하세요.',      // 500
}

// 오류 객체를 받아 화면에 띄울 문장을 돌려준다.
export function errorMessage(err) {
  // 서버가 꺼져 있으면 fetch가 응답 자체를 못 받아 TypeError가 난다.
  if (err instanceof TypeError) return '서버에 연결할 수 없습니다. 백엔드가 실행 중인지 확인하세요.'
  // 대응표에 있으면 그 문장을, 없으면 오류 코드를 그대로 보여준다.
  return MESSAGES[err.code] ?? `요청에 실패했습니다 (${err.code ?? err.message})`
}
